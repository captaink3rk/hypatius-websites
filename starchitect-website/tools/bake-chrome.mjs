/* Remove any block this script inserted before, so re-runs are idempotent
   rather than cumulative. */
function strip(html) {
  const re = new RegExp(
    BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' +
    END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?', 'g');
  return html.replace(re, '');
}

let changed = [], skipped = [];
for (const file of readdirSync(SITE).filter(f => f.endsWith('.html')).sort()) {
  const path = join(SITE, file);
  const orig = readFileSync(path, 'utf8');
  const m = orig.match(/<body([^>]*)>/i);
  if (!m || !/data-chrome=["'](?:on|baked)["']/.test(m[1])) { skipped.push(file); continue; }
  const route = (m[1].match(/data-route=["']([^"']+)["']/) || [, ''])[1];

  let html = strip(orig);
  html = html.replace(new RegExp(
    HBEGIN.replace(/[.*+?^${}()|[\]\\]/g,'\\$&') + '[\\s\\S]*?' +
    HEND.replace(/[.*+?^${}()|[\]\\]/g,'\\$&') + '\\n?', 'g'), '');
  html = html.replace(/<\/head>/i, `${HEAD_CSS}\n</head>`);
  // data-chrome flips to "baked" so home-fx.js knows to stand down. Keeping the
  // attribute (rather than deleting it) means the page still declares that it
  // HAS chrome, which is what the harness checks for.
  html = html.replace(/<body([^>]*)>/i, (all, attrs) =>
    `<body${attrs.replace(/data-chrome=["'](?:on|baked)["']/, 'data-chrome="baked"')}>`);
  html = html.replace(/(<body[^>]*>)/i, `$1\n${head(route)}`);
  html = html.replace(/<\/body>/i, `${foot()}\n</body>`);

  if (html !== orig) { changed.push(file); if (!CHECK) writeFileSync(path, html); }
}

console.log(`baked ${changed.length} page(s): ${changed.join(', ')}`);
console.log(`skipped ${skipped.length} (no data-chrome="on"): ${skipped.join(', ')}`);
if (CHECK && changed.length) { console.error('--check: pages are out of date'); process.exit(1); }
