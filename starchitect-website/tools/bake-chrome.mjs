             'foreign person without prior U.S. Government authorization.';
const WM = 'assets/wordmark.png';

const BEGIN = '<!-- @chrome:begin  generated by tools/bake-chrome.mjs — do not hand-edit -->';
const END   = '<!-- @chrome:end -->';
const HBEGIN = '<!-- @chrome-head:begin  generated — do not hand-edit -->';
const HEND   = '<!-- @chrome-head:end -->';

/* Every page carries its own inline <style> in the head, AFTER all four
   stylesheet links. That block wins the cascade over site-v10.css no matter
   where the link sits, which is why the focus ring declared there never
   reached a focused .nav-logo: the computed outline came back
   `currentColor solid 0px`. Rather than fight it with !important in a file that
   still loses, the focus ring is emitted here, last in the head, where nothing
   in the page can outrank it. Everything else stays in site-v10.css. */
const HEAD_CSS = `${HBEGIN}
<style>
.skip.skip-to-main{position:absolute;width:1px;height:1px;margin:-1px;padding:0;overflow:hidden;
  clip:rect(0 0 0 0);clip-path:inset(50%);white-space:nowrap;border:0}
.skip.skip-to-main:focus{position:fixed;left:8px;top:8px;width:auto;height:auto;margin:0;overflow:visible;
  clip:auto;clip-path:none;z-index:200;background:#D4A03B;color:#060B17;padding:12px 18px;
  font-family:'Rajdhani',sans-serif;font-weight:700;letter-spacing:.04em;
  outline:2px solid #EFE9DD;outline-offset:2px}
.nav-logo:focus,.nav-links > a:focus,.nav-toggle:focus,.footer a:focus,.btn:focus,
.nav-logo:focus-visible,.nav-links > a:focus-visible,.nav-toggle:focus-visible,
.footer a:focus-visible,.btn:focus-visible{outline:2px solid #D4A03B;outline-offset:3px;border-radius:2px}
</style>
${HEND}`;

